inline jl_grid_section section(double start, double bpm, double anchor, int barPhase, int phrasePhase,
                               float phraseConfidence, uint32_t firstBar, uint32_t barCount) {
    jl_grid_section s{};
    s.start_seconds = start;
    s.bpm = bpm;
    s.anchor_seconds = anchor;
    s.bar_phase = static_cast<int8_t>(barPhase);
    s.phrase_phase_bars = static_cast<int8_t>(phrasePhase);
    s.phrase_confidence = phraseConfidence;
    s.first_bar = firstBar;
    s.bar_count = barCount;
    return s;
}

